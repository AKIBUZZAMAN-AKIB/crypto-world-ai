#!/usr/bin/env node
// Generate the inline editor worker for the pinned Monaco version. Keeping the worker
// as source data allows the standalone page to work without a CDN or a separate file.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const result = await build({
    entryPoints: [resolve('node_modules/monaco-editor/esm/vs/editor/editor.worker.js')],
    bundle: true,
    write: false,
    format: 'iife',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    logLevel: 'warning',
});
const worker = result.outputFiles[0].text;
await writeFile('src/vendor/monaco-editor-worker.ts',
    `// Generated by tools/build-monaco-worker.mjs from Monaco Editor 0.45.0 (MIT).\n` +
    `// Rebuild when the pinned dependency changes; do not edit the string by hand.\n` +
    `export const MONACO_EDITOR_WORKER = ${JSON.stringify(worker)};\n`);
console.log(`Inline Monaco worker: ${worker.length} characters`);
